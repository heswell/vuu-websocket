import type { DataTable } from "@heswell/vuu-server";
import type { VuuRowDataItemType } from "@vuu-ui/vuu-protocol-types";
import { LIMIT_ENTITIES, LIMIT_METRICS } from "./referenceData";
import { isBlank, type LimitValues } from "./validation";

export type LimitStatus = "Pending" | "Active";

/** A saved change to one limit, from an edit or import session. */
export type LimitChange =
  | { action: "addRow" | "editCell"; key: string; values: LimitValues }
  | { action: "deleteRow"; key: string };

/** A held change to an Active limit, applied on the next business day. */
type PendingChange =
  | { type: "amend"; values: LimitValues }
  | { type: "delete" };

const startOfDay = (time: number) => {
  const day = new Date(time);
  day.setHours(0, 0, 0, 0);
  return day.getTime();
};

/**
 * The business day a time falls in, as the start of that day. Saturday and
 * Sunday belong to the Friday before.
 */
export const businessDay = (time: number) => {
  const day = new Date(startOfDay(time));
  const weekday = day.getDay();
  if (weekday === 6) day.setDate(day.getDate() - 1);
  if (weekday === 0) day.setDate(day.getDate() - 2);
  return day.getTime();
};

const describeAmendment = (current: LimitValues, values: LimitValues) =>
  Object.entries(values)
    .filter(([column, value]) => current[column] !== value)
    .map(([column, value]) => `${column} ${current[column]} → ${value}`)
    .join(", ");

/**
 * Limit definitions and the changes waiting for the next business day:
 *
 * - a saved change never alters an Active limit. A new limit is Pending.
 *   A change to, or deletion of, an Active limit is held, described in
 *   `change`, and the limit is Pending.
 * - when the business day changes, Pending limits become Active, with their
 *   held changes applied, see {@link activatePendingLimits}.
 */
export class LimitsStore {
  /** Keys of the limits that have been Active, whose changes are held. */
  #activeKeys = new Set<string>();
  #businessDay: number;
  #nextLimitId = 1;
  #pendingChanges = new Map<string, PendingChange>();
  #table: DataTable;

  constructor(table: DataTable, now = Date.now()) {
    this.#table = table;
    this.#businessDay = businessDay(now);
  }

  get table() {
    return this.#table;
  }

  /** limit_id is generated by the server. */
  nextLimitId() {
    return `LIM-${String(this.#nextLimitId++).padStart(4, "0")}`;
  }

  values(key: string): LimitValues | undefined {
    const row = this.#table.getRowAtKey(key, false);
    if (row === undefined) return undefined;
    const { columnMap } = this.#table;
    return Object.fromEntries(
      this.#table.schema.columns.map(({ name }) => [name, row[columnMap[name]]]),
    );
  }

  /** Apply the changes saved in a session, all of them already validated. */
  save(changes: readonly LimitChange[], user: string) {
    for (const change of changes) {
      const current = this.values(change.key);
      if (change.action === "deleteRow") {
        this.#deleteLimit(change.key, user);
      } else if (current === undefined) {
        this.#insert(change.key, change.values, user);
      } else {
        this.#amendLimit(change.key, current, change.values, user);
      }
    }
  }

  /**
   * The start of the next business day: Pending limits become Active, with
   * their held changes applied, and pending deletes take effect.
   */
  activatePendingLimits() {
    const { columnMap } = this.#table;
    const pendingKeys = this.#table.rows
      .filter((row) => row[columnMap.status] === "Pending")
      .map((row) => String(row[columnMap.limit_id]));
    for (const key of pendingKeys) {
      const pending = this.#pendingChanges.get(key);
      this.#pendingChanges.delete(key);
      if (pending?.type === "delete") {
        this.#activeKeys.delete(key);
        this.#table.delete(key);
      } else {
        this.#activeKeys.add(key);
        this.#update(key, {
          ...(pending?.type === "amend" ? pending.values : {}),
          change: "",
          status: "Active",
        });
      }
    }
  }

  /** Activate Pending limits if a new business day has begun. */
  activateOnNewBusinessDay(now = Date.now()) {
    const today = businessDay(now);
    if (today > this.#businessDay) {
      this.#businessDay = today;
      this.activatePendingLimits();
    }
  }

  #update(key: string, values: Record<string, VuuRowDataItemType>) {
    const { columnMap } = this.#table;
    const rowIndex = this.#table.rowIndexAtKey(key);
    const row = this.#table.getRowAtKey(key).slice();
    for (const [column, value] of Object.entries(values)) {
      row[columnMap[column]] = value;
    }
    row[columnMap.vuuUpdatedTimestamp] = Date.now();
    this.#table.update(rowIndex, row);
  }

  #insert(key: string, values: LimitValues, user: string) {
    const now = Date.now();
    const { entity_id, metric } = values;
    const row: LimitValues = {
      ...values,
      change: "New limit",
      changed_by: user,
      effective_from: isBlank(values.effective_from)
        ? startOfDay(now)
        : values.effective_from,
      entity_type:
        LIMIT_ENTITIES.find((entity) => entity.entity_id === entity_id)
          ?.entity_type ?? "",
      limit_id: key,
      metric_family: LIMIT_METRICS[String(metric)].family,
      status: "Pending",
      vuuCreatedTimestamp: now,
      vuuMsg: "",
      vuuUpdatedTimestamp: now,
    };
    this.#table.insert(
      this.#table.schema.columns.map(({ name }) => row[name] ?? ""),
    );
  }

  #amendLimit(
    key: string,
    current: LimitValues,
    values: LimitValues,
    user: string,
  ) {
    if (this.#activeKeys.has(key)) {
      const held = this.#pendingChanges.get(key);
      const amended = {
        ...(held?.type === "amend" ? held.values : {}),
        ...values,
      };
      const change = describeAmendment(current, amended);
      if (change === "") {
        this.#pendingChanges.delete(key);
        this.#update(key, { change: "", changed_by: "", status: "Active" });
      } else {
        this.#pendingChanges.set(key, { type: "amend", values: amended });
        this.#update(key, { change, changed_by: user, status: "Pending" });
      }
    } else {
      // never Active, so the new limit itself is changed
      this.#update(key, {
        ...(values as Record<string, VuuRowDataItemType>),
        change: "New limit",
        changed_by: user,
        status: "Pending",
      });
    }
  }

  #deleteLimit(key: string, user: string) {
    if (this.#activeKeys.has(key)) {
      this.#pendingChanges.set(key, { type: "delete" });
      this.#update(key, { change: "Delete", changed_by: user, status: "Pending" });
    } else {
      this.#table.delete(key);
    }
  }
}
