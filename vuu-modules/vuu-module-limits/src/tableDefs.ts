import {
  SessionTableDef,
  TableDef,
  VUU_DEFAULT_COLUMNS,
  type ColumnDef,
} from "@heswell/vuu-server";
import { ENTITY_LIMIT_METRICS } from "./entityLimits";

export const LIMIT_DEFINITIONS = "limitDefinitions";

/** Columns of a limit that the user enters, in CSV template order. */
const definitionColumns: ColumnDef[] = [
  { name: "entity_id", dataType: "string" },
  { name: "metric", dataType: "string" },
  { name: "scope", dataType: "string" },
  { name: "period", dataType: "string" },
  { name: "warning", dataType: "double" },
  { name: "soft", dataType: "double" },
  { name: "hard", dataType: "double" },
  { name: "currency", dataType: "string" },
  { name: "effective_from", dataType: "epochtimestamp" },
  { name: "effective_to", dataType: "epochtimestamp" },
  { name: "owner", dataType: "string" },
];

export const LIMIT_DEFINITION_COLUMNS = definitionColumns.map(
  ({ name }) => name,
);

/** Columns of a limit that hold a date and time. */
export const LIMIT_TIMESTAMP_COLUMNS = definitionColumns
  .filter(({ dataType }) => dataType === "epochtimestamp")
  .map(({ name }) => name);

/** Columns a limit must have. The others may be blank. */
export const LIMIT_REQUIRED_COLUMNS: readonly string[] = [
  "entity_id",
  "metric",
  "period",
  "hard",
];

/** Columns set when a limit is added, that cannot be changed after. */
export const LIMIT_INSERT_ONLY_COLUMNS: readonly string[] = [
  "entity_id",
  "metric",
  "scope",
  "period",
];

const limitKeyColumn: ColumnDef = { name: "limit_key", dataType: "string" };

/**
 * Limit definitions, one row per limit. limit_key is generated by the
 * server. active is set once a limit has taken effect. change and
 * changed_by describe a change waiting for the next business day.
 */
export const limitDefinitions = TableDef({
  columns: [
    limitKeyColumn,
    { name: "active", dataType: "boolean" },
    { name: "entity_type", dataType: "string" },
    { name: "metric_family", dataType: "string" },
    ...definitionColumns,
    { name: "change", dataType: "string" },
    { name: "changed_by", dataType: "string" },
    ...VUU_DEFAULT_COLUMNS,
  ],
  editable: true,
  keyField: "limit_key",
  name: LIMIT_DEFINITIONS,
});

/**
 * Edit session: the columns a user enters, and editChange, maintained by
 * the server, which describes the change saving each limit will make.
 */
export const editLimitDefinitions = SessionTableDef({
  columns: [
    limitKeyColumn,
    ...definitionColumns,
    { name: "editChange", dataType: "string" },
  ],
  keyField: "limit_key",
  name: `edit-${LIMIT_DEFINITIONS}`,
});

/** Import session: the columns a user enters, and the CSV row number. */
export const importLimitDefinitions = SessionTableDef({
  columns: [
    limitKeyColumn,
    ...definitionColumns,
    { name: "vuuRowNum", dataType: "int" },
  ],
  keyField: "limit_key",
  name: `import-${LIMIT_DEFINITIONS}`,
});

/** Export session: every column. */
export const exportLimitDefinitions = SessionTableDef({
  columns: limitDefinitions.columns,
  keyField: "limit_key",
  name: `export-${LIMIT_DEFINITIONS}`,
});

export const ENTITIES = "entities";
export const ENTITY_LIMITS = "entityLimits";

const entityIdColumn: ColumnDef = { name: "entity_id", dataType: "string" };

/** The entities limits attach to, as a tree: parent_id names the parent. */
export const entities = TableDef({
  columns: [
    entityIdColumn,
    { name: "parent_id", dataType: "string" },
    { name: "entity_type", dataType: "string" },
    { name: "name", dataType: "string" },
  ],
  keyField: "entity_id",
  name: ENTITIES,
});

/**
 * Limits by entity, one row per entity. Each metric has the entity's own
 * value, blank when not set, and `<metric>_eff`, the value that applies,
 * resolved down the tree by the server.
 */
const entityLimitColumns: ColumnDef[] = [
  entityIdColumn,
  { name: "parent_id", dataType: "string" },
  { name: "name", dataType: "string" },
  { name: "entity_type", dataType: "string" },
  ...ENTITY_LIMIT_METRICS.flatMap<ColumnDef>(({ column, effectiveColumn }) => [
    { name: column, dataType: "double" },
    { name: effectiveColumn, dataType: "double" },
  ]),
];

export const entityLimits = TableDef({
  columns: [...entityLimitColumns, ...VUU_DEFAULT_COLUMNS],
  editable: true,
  keyField: "entity_id",
  name: ENTITY_LIMITS,
});

/** Edit session: every column. The server keeps the effective values. */
export const editEntityLimits = SessionTableDef({
  columns: entityLimitColumns,
  keyField: "entity_id",
  name: `edit-${ENTITY_LIMITS}`,
});
